"""Build the Stage B packet: the H1 counterfactual applied to the final candidate W2.

Usage: python make_stage_b_packet.py <worktree_root> <out_dir> <source_commit> [manifest_path]

1. Builds the first packet (files 00 to 06) with make_stage_packet.py.
2. Replaces files 00 and 06 with the Stage B versions.
3. Adds the premise (07), the focused revision instruction (08), the H1-from-W2 candidate (09),
   and a mechanical change list (10). The candidate is derived with make_h1_path.py from a
   temporary copy of the committed W2, so the recorded base is not changed.

The change list is generated by identifier comparison. It is a record of what changed,
not a judgment about what should change.
"""
import json
import pathlib
import subprocess
import sys
import tempfile

root = pathlib.Path(sys.argv[1]).resolve()
out = pathlib.Path(sys.argv[2]).resolve()
commit = sys.argv[3]
manifest_path = pathlib.Path(sys.argv[4]) if len(sys.argv) > 4 else None
exp_rel = "experiments/series-architecture-30-book-construction"
v1_rel = "experiments/series-architecture-30-book-v1"
ver_rel = "experiments/series-architecture-30-book-verification"
py = sys.executable
out.mkdir(parents=True, exist_ok=True)

subprocess.run([py, str(root / ver_rel / "evidence" / "make_stage_packet.py"),
                str(root), str(out), commit], check=True, capture_output=True)


def blob(path):
    return subprocess.run(["git", "-C", str(root), "show", f"{commit}:{path}"],
                          capture_output=True, check=True).stdout


def template(name):
    return (root / ver_rel / "review" / "templates" / name).read_text(encoding="utf-8")


(out / "00-reviewer-instructions.md").write_text(template("00-reviewer-instructions-stageB.md"), encoding="utf-8")
(out / "06-source-identity.md").write_text(template("06-source-identity-stageB.md"), encoding="utf-8")

premise = blob(f"{v1_rel}/evidence/revision-instruction.txt").decode("utf-8")
(out / "07-h1-premise.md").write_text(
    "# H1 premise (author-proposed counterfactual; not accepted)\n\n"
    f"Source: `{v1_rel}/evidence/revision-instruction.txt`, verbatim.\n\n" + premise,
    encoding="utf-8")
(out / "08-h1-focused-instruction.txt").write_bytes(blob(f"{exp_rel}/evidence/instruction-h1.txt"))

with tempfile.TemporaryDirectory() as scratch:
    base = pathlib.Path(scratch) / "w2-base.json"
    base.write_bytes(blob(f"{exp_rel}/03-working-candidate-v2.json"))
    subprocess.run([py, str(root / exp_rel / "evidence" / "make_h1_path.py"),
                    str(base), str(out / "09-candidate-H1-from-W2.json")], check=True, capture_output=True)

w2 = json.loads(blob(f"{exp_rel}/03-working-candidate-v2.json").decode("utf-8"))
h1 = json.loads((out / "09-candidate-H1-from-W2.json").read_text(encoding="utf-8"))

lines = [
    "# Changes from W2 to H1-from-W2 (mechanical)", "",
    "Generated by `make_stage_b_packet.py` by comparing file 05 with file 09 by identifier. "
    "This is a record of what changed. It is not a judgment about what should change or be preserved. "
    "Anything not listed here is identical in files 05 and 09.", "",
]
id_keys = {"genre_contracts": "genre_node_id"}
for key in ["nodes", "links", "phases", "emotion_targets", "complex_emotions", "genre_contracts", "genre_interactions"]:
    idf = id_keys.get(key, "id")
    a = {x[idf]: x for x in w2[key]}
    b = {x[idf]: x for x in h1[key]}
    added = sorted(set(b) - set(a))
    removed = sorted(set(a) - set(b))
    changed = sorted(k for k in set(a) & set(b) if a[k] != b[k])
    lines += [f"## {key}", "", f"Added: {', '.join(added) or 'none'}. Removed: {', '.join(removed) or 'none'}. "
              f"Changed: {', '.join(changed) or 'none'}.", ""]
    for k in added:
        lines += [f"### Added `{k}`", "", "```json", json.dumps(b[k], ensure_ascii=False, indent=2), "```", ""]
    for k in changed:
        lines += [f"### Changed `{k}`", "", "Before (W2):", "", "```json",
                  json.dumps(a[k], ensure_ascii=False, indent=2), "```", "", "After (H1):", "", "```json",
                  json.dumps(b[k], ensure_ascii=False, indent=2), "```", ""]
for key in ["summary", "open_questions"]:
    if w2[key] != h1[key]:
        lines += [f"## Top-level `{key}`", "", "Before (W2):", "", "```json",
                  json.dumps(w2[key], ensure_ascii=False, indent=2), "```", "", "After (H1):", "", "```json",
                  json.dumps(h1[key], ensure_ascii=False, indent=2), "```", ""]
(out / "10-h1-changes.md").write_text("\n".join(lines), encoding="utf-8")

if manifest_path:
    def sha(p):
        return subprocess.run(["sha256sum", str(p)], capture_output=True, text=True).stdout.split()[0]
    files = sorted(p for p in out.iterdir() if p.is_file())
    manifest = {
        "packet": "stage-B",
        "source_commit": commit,
        "builder": f"{ver_rel}/evidence/make_stage_b_packet.py",
        "files": [{"path": p.name, "sha256": sha(p), "bytes": p.stat().st_size} for p in files],
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
for p in sorted(out.iterdir()):
    if p.is_file():
        print(p.name, p.stat().st_size)
